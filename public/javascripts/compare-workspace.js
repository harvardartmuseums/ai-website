(function() {
  var diffActive = false;
  var densityVisible = false;
  var costVisible = false;

  function applyPanelVisibility() {
    document.querySelectorAll('#research-compare .panel-stats-section--density').forEach(function(el) {
      el.style.display = densityVisible ? '' : 'none';
    });
    document.querySelectorAll('#research-compare .panel-stats-section--cost').forEach(function(el) {
      el.style.display = costVisible ? '' : 'none';
    });
  }

  function getDescData(key) {
    return document.querySelector('.desc-data[data-key="' + key + '"]');
  }

  function renderPanel(panelEl, headerEl, key) {
    var el = getDescData(key);
    if (!el) return;
    panelEl.innerHTML = el.innerHTML;
    var source = el.dataset.source;
    var model = el.dataset.model;
    var date = el.dataset.date;
    var html = '<span class="header-scope">' + escapeHtml(el.dataset.scope || '')
      + (el.dataset.annotationId ? ' · Annotation ' + escapeHtml(el.dataset.annotationId) : '') + '</span>';
    if (date && date !== '?') {
      var age = el.dataset.age || '';
      html += '<span class="header-date">Description generated on ' + escapeHtml(date);
      if (age) html += ' <span class="header-age">(' + age + ')</span>';
      html += '</span>';
    }
    var usageInput  = el.dataset.usageInput;
    var usageOutput = el.dataset.usageOutput;
    var stats = null;
    if (el.dataset.statsTotal) {
      stats = {
        total:          parseInt(el.dataset.statsTotal,   10),
        lexicalDensity: parseInt(el.dataset.statsDensity, 10),
        ttr:            parseInt(el.dataset.statsTtr,     10),
        hapaxRatio:     parseInt(el.dataset.statsHapax,   10),
        avgSentLen:     parseInt(el.dataset.statsSent,    10)
      };
    }
    if (stats) {
      html += '<div class="panel-stats-section panel-stats-section--density">'
        + '<span class="sidebar-group-label panel-stats-label">Information Density</span>'
        + '<div class="panel-stats">'
        + '<span class="panel-stat" title="Content words / total words">Lexical density <strong>' + stats.lexicalDensity + '%</strong></span>'
        + '<span class="panel-stat" title="Unique words / total words">Vocab diversity <strong>' + stats.ttr + '%</strong></span>'
        + '<span class="panel-stat" title="Words appearing once / total words">Specificity <strong>' + stats.hapaxRatio + '%</strong></span>'
        + '<span class="panel-stat" title="Average words per sentence">Avg sentence <strong>' + stats.avgSentLen + ' words</strong></span>'
        + '<span class="panel-stat" title="Total word count">Length <strong>' + stats.total + ' words</strong></span>'
        + '</div>'
        + '</div>';
    }
    if (source !== 'Human' && (usageInput || usageOutput)) {
      var totalTokens = null;
      if (usageInput !== '' && usageOutput !== '' && Number.isFinite(Number(usageInput)) && Number.isFinite(Number(usageOutput))) {
        totalTokens = Number(usageInput) + Number(usageOutput);
      }
      html += '<div class="panel-stats-section panel-stats-section--cost">'
        + '<span class="sidebar-group-label panel-stats-label">Token usage</span>'
        + '<div class="panel-stats panel-stats--tokens">'
        + '<span class="panel-stat" title="Tokens sent to the model">Input tokens <strong>' + (usageInput || '—') + '</strong></span>'
        + '<span class="panel-stat" title="Tokens generated by the model">Output tokens <strong>' + (usageOutput || '—') + '</strong></span>'
        + (totalTokens !== null ? '<span class="panel-stat" title="Total tokens used">Total tokens <strong>' + totalTokens + '</strong></span>' : '')
        + '</div>'
        + '</div>';
    }
    headerEl.innerHTML = html;
  }

  function updateSimilarity() {
    if (document.getElementById('research-compare').hidden) return;
    var textA = document.getElementById('panel-a').innerText;
    var textB = document.getElementById('panel-b').innerText;
    var tfidf = tfidfCosine(textA, textB);
    var overlap = wordOverlap(textA, textB);
    var sentence = sentenceOverlap(textA, textB);
    var phrases = keyPhrases(textA, textB);
    document.getElementById('tfidf-fill').style.width = tfidf + '%';
    document.getElementById('tfidf-label').textContent = tfidf + '%';
    document.getElementById('overlap-fill').style.width = overlap.pct + '%';
    document.getElementById('overlap-label').textContent = overlap.pct + '%';
    document.getElementById('similarity-counts').textContent =
      '(' + overlap.shared + ' shared / ' + overlap.uniqueA + ' only A / ' + overlap.uniqueB + ' only B)';
    document.getElementById('sentence-fill').style.width = sentence.pct + '%';
    document.getElementById('sentence-label').textContent = sentence.pct + '%';
    document.getElementById('sentence-counts').textContent =
      '(' + sentence.matchedA + ' of ' + sentence.totalA + ' in A / ' + sentence.matchedB + ' of ' + sentence.totalB + ' in B)';
    renderKeyPhrases(phrases);
    document.getElementById('semantic-label').textContent = 'Computing…';
    document.getElementById('semantic-fill').style.width = '0%';
    if (window.__updateSemantic) window.__updateSemantic(textA, textB);
  }

  function renderKeyPhrases(result) {
    var out = document.getElementById('keyphrases-output');
    if (!out) return;
    var html = '';
    result.shared.forEach(function(t) {
      html += '<span class="phrase-chip phrase-chip--shared">' + escapeHtml(t) + '</span>';
    });
    result.onlyA.forEach(function(t) {
      html += '<span class="phrase-chip phrase-chip--a">' + escapeHtml(t) + '</span>';
    });
    result.onlyB.forEach(function(t) {
      html += '<span class="phrase-chip phrase-chip--b">' + escapeHtml(t) + '</span>';
    });
    out.innerHTML = html || '<span class="similarity-counts">No significant terms found</span>';
  }

  function applyDiff() {
    var panelA = document.getElementById('panel-a');
    var panelB = document.getElementById('panel-b');
    var textA = panelA.innerText;
    var textB = panelB.innerText;

    var diffResult = Diff.diffWords(textA, textB);

    var htmlA = '';
    var htmlB = '';
    diffResult.forEach(function(part) {
      if (part.removed) {
        htmlA += '<span class="diff-remove">' + escapeHtml(part.value) + '</span>';
      } else if (part.added) {
        htmlB += '<span class="diff-add">' + escapeHtml(part.value) + '</span>';
      } else {
        var escaped = escapeHtml(part.value);
        htmlA += escaped;
        htmlB += escaped;
      }
    });

    panelA.innerHTML = htmlA;
    panelB.innerHTML = htmlB;
  }

  function escapeHtml(str) {
    return str
      .replace(/&/g, '&amp;')
      .replace(/</g, '&lt;')
      .replace(/>/g, '&gt;');
  }

  function clearDiff() {
    var keyA = document.getElementById('select-a').value;
    var keyB = document.getElementById('select-b').value;
    renderPanel(document.getElementById('panel-a'), document.getElementById('header-a'), keyA);
    renderPanel(document.getElementById('panel-b'), document.getElementById('header-b'), keyB);
    applyPanelVisibility();
  }

  function update() {
    clearDiff();
    updateSimilarity();
    if (diffActive) applyDiff();
  }

  document.addEventListener('DOMContentLoaded', function() {
    var selectA = document.getElementById('select-a');
    var selectB = document.getElementById('select-b');
    if (!selectA) return;

    // Prefer image outputs; object references remain explicit choices.
    var aiOptions = Array.from(selectA.options).filter(function(o) { return o.value.indexOf('annotation_') === 0; });
    if (aiOptions.length) { selectA.value = aiOptions[0].value; selectB.value = aiOptions[Math.min(1, aiOptions.length - 1)].value; }
    else if (selectB.options.length > 1) selectB.selectedIndex = 1;

    applyPanelVisibility();
    update();
    document.querySelector(".image-research-workspace").addEventListener("researchview", function(e) { if (e.detail === "compare") update(); });

    selectA.addEventListener('change', update);
    selectB.addEventListener('change', update);

    document.getElementById('diff-toggle').addEventListener('click', function() {
      diffActive = !diffActive;
      this.textContent = diffActive ? 'Hide Diff' : 'Show Diff';
      if (diffActive) {
        applyDiff();
      } else {
        clearDiff();
      }
    });

    document.getElementById('density-toggle').addEventListener('click', function() {
      densityVisible = !densityVisible;
      this.textContent = densityVisible ? 'Hide language statistics' : 'Show language statistics';
      applyPanelVisibility();
    });

    document.getElementById('cost-toggle').addEventListener('click', function() {
      costVisible = !costVisible;
      this.textContent = costVisible ? 'Hide tokens' : 'Show tokens';
      applyPanelVisibility();
    });

    // ── Side panel presets ──────────────────────────────────────

    var CAPTION_MODELS = ['BLIP Caption', 'BLIP-2 Caption', 'CLIP Caption'];

    function getAllDescs() {
      return Array.from(document.querySelectorAll('.desc-data'))
        .filter(function(el) { return CAPTION_MODELS.indexOf(el.dataset.model) === -1; })
        .map(function(el) {
          var text = el.textContent || '';
          var words = text.trim().split(/\s+/).filter(Boolean).length;
          var inp = el.dataset.usageInput  ? parseInt(el.dataset.usageInput,  10) : null;
          var out = el.dataset.usageOutput ? parseInt(el.dataset.usageOutput, 10) : null;
          return {
            key:          el.dataset.key,
            source:       el.dataset.source,
            date:         el.dataset.date,
            modelReleased: el.dataset.modelReleased || null,
            words:        words,
            tokens:       (inp !== null && out !== null) ? inp + out : null
          };
        });
    }

    function applyPreset(keyA, keyB) {
      selectA.value = keyA;
      selectB.value = keyB;
      update();
    }

    document.getElementById('preset-length').addEventListener('click', function() {
      var d = getAllDescs().slice().sort(function(a, b) { return a.words - b.words; });
      if (d.length >= 2) applyPreset(d[0].key, d[d.length - 1].key);
    });

    document.getElementById('preset-cost').addEventListener('click', function() {
      var d = getAllDescs().filter(function(x) { return x.tokens !== null; })
                           .sort(function(a, b) { return a.tokens - b.tokens; });
      if (d.length >= 2) applyPreset(d[0].key, d[d.length - 1].key);
    });

    document.getElementById('preset-age').addEventListener('click', function() {
      var d = getAllDescs().filter(function(x) { return x.modelReleased; })
                           .sort(function(a, b) { return a.modelReleased < b.modelReleased ? -1 : 1; });
      if (d.length >= 2) applyPreset(d[0].key, d[d.length - 1].key);
    });

    (function auditPresets() {
      var withCost = getAllDescs().filter(function(x) { return x.tokens !== null; });
      if (withCost.length < 2) {
        document.getElementById('preset-cost').classList.add('quickbar-btn--disabled');
      }
      var withRelease = getAllDescs().filter(function(x) { return x.modelReleased; });
      if (withRelease.length < 2) {
        document.getElementById('preset-age').classList.add('quickbar-btn--disabled');
      }
      if (getAllDescs().length < 2) {
        document.querySelectorAll('#research-compare .quickbar-btn').forEach(function(b) {
          b.classList.add('quickbar-btn--disabled');
        });
      }
    })();

  });

window.researchCompare = function(a, b) {
  var sa = document.getElementById("select-a"), sb = document.getElementById("select-b");
  if (!sa || !sb) return;
  if (a) sa.value = a;
  if (b) sb.value = b;
  if (sa.value === sb.value && sb.options.length > 1) sb.selectedIndex = sa.selectedIndex === 0 ? 1 : 0;
  update();
};
})();
